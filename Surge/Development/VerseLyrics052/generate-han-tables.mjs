import {readFileSync,writeFileSync} from 'node:fs';
// Repack the same 6,447 Unicode 17.0 mappings. No downloads at build/runtime.
// Plane numbers are shared by a table; each record is two UTF-16 code units.
// There is no full-table expansion or Map construction in a lyric invocation.
const root=new URL('./core/',import.meta.url),file=new URL('spotify-lyrics.js',root);
const chars=[...JSON.parse(readFileSync(new URL('test/fixtures/han-reference.json',root))).pairs];
const groups=new Map();
for(let i=0;i<chars.length;i+=2){
  const key=chars[i].codePointAt(0),value=chars[i+1].codePointAt(0),group=(key>>>16)+','+(value>>>16);
  if(!groups.has(group))groups.set(group,[]);groups.get(group).push([key&65535,value&65535]);
}
const rows=[...groups].sort(([a],[b])=>a.localeCompare(b)).map(([planes,pairs])=>{
  pairs.sort((a,b)=>a[0]-b[0]);
  return '  ['+planes+','+JSON.stringify(pairs.map(([k,v])=>String.fromCharCode(k,v)).join(''))+']';
});
const source=readFileSync(file,'utf8'),start=source.indexOf('// BEGIN GENERATED HAN VARIANTS'),end=source.indexOf('function hanVariant(');
if(start<0||end<start)throw Error('Han table boundaries');
writeFileSync(file,source.slice(0,start)+`// BEGIN GENERATED HAN VARIANTS
// Unicode 17.0.0 Unihan kSimplifiedVariant; see NOTICE-UNICODE.txt.
// Generated by generate-han-tables.mjs; sorted [source plane,target plane,pairs].
// Each pair stores low 16-bit key/value units, never a decoded runtime map.
let HAN_TABLES;
function hanTables() {
  return HAN_TABLES || (HAN_TABLES = [
${rows.join(',\n')}
  ]);
}
// END GENERATED HAN VARIANTS
`+source.slice(end));
console.log(JSON.stringify({pairs:chars.length/2,tables:groups.size,tableBytes:Buffer.byteLength(rows.join(',\n'))}));
