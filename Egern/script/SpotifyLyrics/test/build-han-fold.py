"""Build the metadata-only Han variant table from Unicode 17.0.0 data.

No third-party implementation is used. Supply Unihan_Variants.txt extracted
from https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip locally.
Only single, unambiguous kSimplifiedVariant values are accepted.
Data license: ../NOTICE-UNICODE.txt. The generated JS has no runtime dependency.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

EXPECTED_SHA256 = "3f23cd71872633f3350875d25bd388e83b60fa71807634c9a600ec26f38a68ab"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("variants", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
data = args.variants.read_bytes()
if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
    raise SystemExit("Unexpected Unicode data revision; use the pinned 17.0.0 source")
pairs = {}
for line in data.decode("utf-8").splitlines():
    if not line or line.startswith("#"):
        continue
    source, prop, target = line.split("\t", 2)
    values = target.split()
    if prop != "kSimplifiedVariant" or len(values) != 1:
        continue
    match = re.fullmatch(r"U\+([0-9A-F]+)", values[0])
    if match:
        original, simplified = chr(int(source[2:], 16)), chr(int(match[1], 16))
        if original != simplified:
            pairs[original] = simplified
# Resolve unambiguous chains to make matching idempotent; omit cycles.
folded = {}
for original, simplified in pairs.items():
    visited = {original}
    while simplified in pairs and simplified not in visited:
        visited.add(simplified)
        simplified = pairs[simplified]
    if simplified not in visited:
        folded[original] = simplified
packed = "".join(a + b for a, b in sorted(folded.items()))
block = "\n".join([
    "// BEGIN GENERATED HAN VARIANTS",
    "// Unicode 17.0.0 Unihan kSimplifiedVariant data; see NOTICE-UNICODE.txt.",
    "// Generated by test/build-han-fold.py; no third-party runtime code.",
    "const HAN_FOLD_PAIRS = " + json.dumps(packed, ensure_ascii=False) + ";",
    "const HAN_FOLD = new Map();",
    "{ const chars = Array.from(HAN_FOLD_PAIRS); for (let i = 0; i < chars.length; i += 2) HAN_FOLD.set(chars[i], chars[i + 1]); }",
    "// END GENERATED HAN VARIANTS",
])
script = Path(__file__).resolve().parent.parent / "spotify-lyrics.js"
text = script.read_text()
pattern = r"// BEGIN GENERATED HAN VARIANTS\n.*?// END GENERATED HAN VARIANTS"
current = re.search(pattern, text, re.S)
if not current:
    raise SystemExit("Generated block not found")
if args.check:
    if current[0] != block:
        raise SystemExit("Generated table differs from the pinned data")
else:
    script.write_text(text[:current.start()] + block + text[current.end():])
print(json.dumps({"pairs": len(folded), "data_sha256": EXPECTED_SHA256, "status": "passed"}))
