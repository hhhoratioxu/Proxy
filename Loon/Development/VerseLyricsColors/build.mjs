import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const core = read('./core/spotify-lyrics.js');
if (!core.includes('const VERSION = "0.4.2";')) throw Error('Unexpected core version');
const stripped = core.replace(/^export default async function\(ctx\)/m, 'async function verseLyricsCore(ctx)').replace(/^export\s*\{[^}]*\};\s*/gm, '');
if (/^export\s/m.test(stripped)) throw Error('Unhandled export');
const folder = new URL('./runtime/Loon/script/', import.meta.url);
mkdirSync(folder, {recursive:true});
const body = `/* VerseLyrics Loon adapter 1; core 0.4.2.\n * Original host bridge and color handling. No external JavaScript runtime.\n */\n/*\n${read('./core/NOTICE-UNICODE.txt')}*/\n(() => {\n"use strict";\n${stripped}\n${read('./native-adapter.js').replace('__CLIENT__', 'Loon')}\n})();\n`;
writeFileSync(new URL('SpotifyLyrics.js', folder), body);
console.log(JSON.stringify({client:'Loon',version:'0.4.2',bytes:Buffer.byteLength(body),sha256:createHash('sha256').update(body).digest('hex')}));
